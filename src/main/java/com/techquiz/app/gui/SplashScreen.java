class SplashThread extends Thread{
    public void run(){
        boolean databaseReady = DBInitializer.initialize();

        if (!databaseReady) {
            SwingUtilities.invokeLater(() -> {
                JOptionPane.showMessageDialog(
                        null,
                        "Unable to initialize database.",
                        "Database Error",
                        JOptionPane.ERROR_MESSAGE
                );

                System.exit(1);
            });
            return;
        }
        int count = 1;
        Random random = new Random();
        while(jProgressBar1.getValue() < jProgressBar1.getMaximum()){
            try {
                jProgressBar1.setValue(count);
                Thread.sleep(1200);
                count = count + random.nextInt(100);
            } catch (InterruptedException e) {
                JOptionPane.showMessageDialog(null, "Exception In Thread : "+ e, "Error !!!", JOptionPane.ERROR_MESSAGE );
            }
        }
        dispose();
        LoginFrame loginFrame = new LoginFrame();
        loginFrame.setVisible(true);
    }
}
    
